android {
  namespace = "com.manglamfertilizer.app"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.manglamfertilizer.app"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    val keystorePropsFile = rootProject.file("keystore.properties")
    val keystoreProps = Properties().apply {
      if (keystorePropsFile.exists()) {
        FileInputStream(keystorePropsFile).use { load(it) }
      }
    }

    create("release") {
      val customPath = System.getenv("KEYSTORE_PATH")
        ?: keystoreProps.getProperty("storeFile")
        ?: "${rootDir}/my-upload-key.jks"
      val resolvedFile = file(customPath)
      if (resolvedFile.exists()) {
        storeFile = resolvedFile
        storePassword = System.getenv("STORE_PASSWORD") ?: keystoreProps.getProperty("storePassword") ?: "android"
        keyAlias = System.getenv("KEY_ALIAS") ?: keystoreProps.getProperty("keyAlias") ?: "upload"
        keyPassword = System.getenv("KEY_PASSWORD") ?: keystoreProps.getProperty("keyPassword") ?: "android"
      } else {
        // Do not configure debug.keystore as a fallback for release builds.
        // Release builds require a dedicated production keystore.
        storeFile = null
      }
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug { signingConfig = signingConfigs.getByName("debugConfig") }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
  lint {
    abortOnError = true
    checkReleaseBuilds = true
    disable.add("InvalidFragmentVersionForActivityResult")
  }
}

tasks.matching { it.name.startsWith("validateSigningRelease") || it.name.startsWith("packageRelease") }.configureEach {
  doFirst {
    val releaseConfig = android.signingConfigs.getByName("release")
    if (releaseConfig.storeFile == null || !releaseConfig.storeFile!!.exists()) {
      throw GradleException("Production release keystore is not configured. Build aborted.")
    }
  }
}

